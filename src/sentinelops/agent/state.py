"""
LangGraph Investigation State Schema for SentinelOps.

Defines the typed state passed across nodes in the LangGraph workflow:
- `InvestigationState`: Central typed dictionary carrying structured investigation context.

Architectural Rule:
Nodes communicate via structured models (Incident, InvestigationPlan, InvestigationEvidence,
Hypothesis, Diagnosis, VerificationResult) rather than large prompt-formatted strings.
"""
from __future__ import annotations

from typing import Any, TypedDict

from sentinelops.domain.models.incident import Incident
from sentinelops.domain.models.investigation import (
    Diagnosis,
    Hypothesis,
    InvestigationEvidence,
    InvestigationPlan,
    InvestigationResult,
    InvestigationStatus,
    VerificationResult,
)


class InvestigationState(TypedDict):
    """
    Typed dictionary representing the full state of an incident investigation run.

    Fields:
        incident: Canonical `Incident` under investigation.
        investigation_plan: Structured plan generated by the planner node.
        current_step: Current step index in the plan.
        iteration: Current iteration loop counter (bounded by max_iterations).
        max_iterations: Maximum investigation loops allowed before halting.
        evidence: Cumulative list of structured `InvestigationEvidence` gathered.
        hypotheses: Formulated root cause hypotheses.
        selected_hypothesis: Top candidate hypothesis selected for diagnosis.
        diagnosis: Evidence-backed root cause diagnosis.
        confidence: Evaluated confidence score.
        verification_result: Outcome from verification gate.
        status: Current investigation status enum value.
        errors: Log of non-fatal errors or warnings encountered.
        tool_calls_summary: Audit list of capability queries executed.
        start_time_iso: ISO timestamp when investigation began.
        final_result: Completed immutable `InvestigationResult` record.
    """

    incident: Incident
    investigation_plan: InvestigationPlan | None
    current_step: int
    iteration: int
    max_iterations: int
    evidence: list[InvestigationEvidence]
    hypotheses: list[Hypothesis]
    selected_hypothesis: Hypothesis | None
    diagnosis: Diagnosis | None
    confidence: float
    verification_result: VerificationResult | None
    status: InvestigationStatus
    errors: list[str]
    tool_calls_summary: list[dict[str, Any]]
    start_time_iso: str
    final_result: InvestigationResult | None
