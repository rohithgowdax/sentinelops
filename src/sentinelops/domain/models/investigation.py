"""
Canonical investigation domain models for SentinelOps Slice 2.

Defines structured, typed entities used by the LangGraph AI investigation loop:
- `InvestigationPlan`: Steps planned to diagnose the incident.
- `InvestigationEvidence`: Structured evidence collected from capabilities.
- `Hypothesis`: Plausible root causes generated from evidence correlation.
- `Diagnosis`: Final root cause explanation backed by specific evidence IDs.
- `VerificationResult`: Outcome of the verification gate.
- `InvestigationResult`: Immutable record of the completed investigation.

Architectural Rule:
All AI agent communication and persistence must utilize these typed contracts
instead of free-form strings.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class InvestigationStatus(str, Enum):
    """
    Lifecycle status of an AI incident investigation.

    Attributes:
        INVESTIGATING: Active investigation running through graph nodes.
        DIAGNOSED: Root cause identified with verified supporting evidence.
        INSUFFICIENT_EVIDENCE: Max iterations reached without sufficient evidence.
        INVESTIGATION_FAILED: Fatal error or unhandled failure during graph execution.
    """

    INVESTIGATING = "investigating"
    DIAGNOSED = "diagnosed"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"
    INVESTIGATION_FAILED = "investigation_failed"


class InvestigationStep(BaseModel):
    """
    A single planned step in an investigation plan.

    Fields:
        id: Unique step identifier (e.g. 'telemetry_check', 'baseline_comparison').
        description: Human-readable description of what this step investigates.
        capability: Target capability concept ('telemetry', 'baseline', 'trigger_context').
        params: Parameters passed to capability tools.
    """

    id: str = Field(description="Step identifier (e.g. 'telemetry_check').")
    description: str = Field(description="Actionable explanation of the investigation step.")
    capability: str = Field(
        default="telemetry",
        description="Generic capability category required (e.g. 'telemetry', 'baseline').",
    )
    params: dict[str, Any] = Field(
        default_factory=dict,
        description="Optional parameters for tool execution.",
    )


class InvestigationPlan(BaseModel):
    """
    Structured plan generated by the planning node.

    Fields:
        steps: List of ordered investigation steps.
        rationale: Explains why these steps were chosen based on incident trigger context.
    """

    steps: list[InvestigationStep] = Field(
        default_factory=list,
        description="Sequential list of investigation steps.",
    )
    rationale: str = Field(
        default="",
        description="Summary explanation of the planned investigation approach.",
    )


class InvestigationEvidence(BaseModel):
    """
    Canonical structured evidence item collected by capability tools.

    Fields:
        evidence_id: Stable identifier referenced by hypotheses and diagnoses (e.g. 'E01').
        incident_id: ID of the incident being investigated.
        source_type: Category of capability ('telemetry', 'baseline_comparison', 'trigger_context').
        source_ref: Specific metric name, rule, or record ID referenced.
        timestamp_window: Time window bounds {'start': ISO, 'end': ISO}.
        resource: Affected service or host name.
        signal: Canonical metric name or signal type.
        observation: Structured observation metrics (baseline, observed_max, observed_avg, samples).
        relevance: Explanation of how this evidence relates to the failure.
        raw_reference: Optional underlying event_id or row pointer.
    """

    evidence_id: str = Field(
        default_factory=lambda: f"E{uuid.uuid4().hex[:6].upper()}",
        description="Unique evidence identifier referenced by diagnoses.",
    )
    incident_id: str = Field(
        description="ID of the incident under investigation.",
    )
    source_type: str = Field(
        description="Capability source ('telemetry', 'baseline_comparison', 'trigger_context').",
    )
    source_ref: str = Field(
        description="Source identifier (metric name or rule ID).",
    )
    timestamp_window: dict[str, str] = Field(
        default_factory=dict,
        description="Start and end ISO timestamps of the query window.",
    )
    resource: str = Field(
        description="Target service or resource name.",
    )
    signal: str = Field(
        default="",
        description="Metric name or signal investigated.",
    )
    observation: dict[str, Any] = Field(
        default_factory=dict,
        description="Structured observation numbers (baseline, observed_max, observed_avg).",
    )
    relevance: str = Field(
        default="",
        description="Diagnostic relevance of this evidence.",
    )
    raw_reference: str | None = Field(
        default=None,
        description="Audit trace link to specific TelemetryRecord or event ID.",
    )
    # Slice 3 Knowledge-Grounding extensions
    kind: str = Field(
        default="telemetry",
        description="Evidence category ('telemetry', 'knowledge', 'log', 'trace', 'change').",
    )
    document_id: str | None = Field(
        default=None,
        description="Knowledge document identifier if source is knowledge.",
    )
    chunk_id: str | None = Field(
        default=None,
        description="Knowledge chunk identifier if source is knowledge.",
    )
    source: str | None = Field(
        default=None,
        description="Document source or filepath if source is knowledge.",
    )
    document_type: str | None = Field(
        default=None,
        description="Document classification (runbook, postmortem, etc.).",
    )
    retrieval_score: float | None = Field(
        default=None,
        description="Search score from vector/hybrid retrieval.",
    )
    rank: int | None = Field(
        default=None,
        description="Rank position in search results.",
    )
    content_snippet: str | None = Field(
        default=None,
        description="Excerpt or snippet of the retrieved text.",
    )



class Hypothesis(BaseModel):
    """
    Plausible failure cause formulated during evidence analysis.

    Fields:
        hypothesis_id: Unique ID for this hypothesis (e.g. 'H01').
        hypothesis: Clear description of the proposed root cause.
        confidence: Confidence score from 0.0 to 1.0.
        supporting_evidence_ids: List of evidence_ids directly supporting this hypothesis.
        contradicting_evidence_ids: List of evidence_ids contradicting this hypothesis.
    """

    hypothesis_id: str = Field(
        default_factory=lambda: f"H{uuid.uuid4().hex[:4].upper()}",
        description="Unique hypothesis identifier.",
    )
    hypothesis: str = Field(
        description="Description of the proposed failure hypothesis.",
    )
    confidence: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Confidence score between 0.0 and 1.0.",
    )
    supporting_evidence_ids: list[str] = Field(
        default_factory=list,
        description="List of evidence_ids that support this hypothesis.",
    )
    contradicting_evidence_ids: list[str] = Field(
        default_factory=list,
        description="List of evidence_ids that contradict this hypothesis.",
    )


class Diagnosis(BaseModel):
    """
    Evidence-backed root cause diagnosis.

    Fields:
        root_cause: Summarized root cause title or statement.
        confidence: Final confidence score (0.0 to 1.0).
        supporting_evidence: Mandatory list of evidence_ids (e.g. ['E01', 'E02']).
        contradicting_evidence: List of unaddressed or resolved contradiction evidence_ids.
        explanation: Detailed reasoning linking evidence to the root cause.
        recommended_actions: Non-executable recommended remediation actions.
    """

    root_cause: str = Field(
        description="Identified root cause of the incident.",
    )
    confidence: float = Field(
        ge=0.0,
        le=1.0,
        description="Diagnostic confidence score between 0.0 and 1.0.",
    )
    supporting_evidence: list[str] = Field(
        default_factory=list,
        description="Mandatory list of valid evidence_ids supporting this diagnosis.",
    )
    contradicting_evidence: list[str] = Field(
        default_factory=list,
        description="List of contradicting evidence_ids considered.",
    )
    explanation: str = Field(
        description="Reasoning explaining how the evidence confirms the root cause.",
    )
    recommended_actions: list[str] = Field(
        default_factory=list,
        description="Non-executable advisory actions recommended for recovery.",
    )
    # Slice 3 Knowledge Grounding extensions
    observed_evidence: list[str] = Field(
        default_factory=list,
        description="Observed telemetry evidence IDs supporting diagnosis.",
    )
    knowledge_evidence: list[str] = Field(
        default_factory=list,
        description="Knowledge base evidence IDs supporting diagnosis.",
    )
    reasoning_summary: str = Field(
        default="",
        description="Concise structured rationale explaining deduction.",
    )
    uncertainties: list[str] = Field(
        default_factory=list,
        description="Remaining operational uncertainties.",
    )



class VerificationResult(BaseModel):
    """
    Verification gate outcome evaluating whether a diagnosis is adequately supported.

    Fields:
        is_verified: True if evidence is sufficient and confidence meets threshold.
        confidence: Evaluated confidence score.
        reason: Explanation of the verification decision.
        missing_evidence: Specific signals or evidence items still required.
        contradictions_found: Contradictions preventing verification.
    """

    is_verified: bool = Field(
        description="Whether the diagnosis passed verification.",
    )
    confidence: float = Field(
        ge=0.0,
        le=1.0,
        description="Confidence evaluated by the verifier.",
    )
    reason: str = Field(
        description="Verification justification or rationale.",
    )
    missing_evidence: list[str] = Field(
        default_factory=list,
        description="List of missing evidence areas if unverified.",
    )
    contradictions_found: list[str] = Field(
        default_factory=list,
        description="Any contradictory signals detected.",
    )


class InvestigationResult(BaseModel):
    """
    Durable outcome of an incident investigation workflow.

    Fields:
        incident_id: ID of the investigated incident.
        status: Final status (DIAGNOSED, INSUFFICIENT_EVIDENCE, INVESTIGATION_FAILED).
        diagnosis: Structured diagnosis if one was produced.
        confidence: Final confidence rating.
        supporting_evidence: Full structured evidence collected.
        investigation_steps: Steps planned and executed.
        tool_calls_summary: Summary of all capability queries performed.
        duration_seconds: Wall-clock execution time.
        iteration_count: Number of investigation loops executed.
        failure_reason: Error message if status is INVESTIGATION_FAILED.
        completed_at: UTC timestamp when the investigation finished.
    """

    incident_id: str = Field(
        description="Canonical ID of the investigated incident.",
    )
    status: InvestigationStatus = Field(
        description="Final investigation outcome status.",
    )
    diagnosis: Diagnosis | None = Field(
        default=None,
        description="Final diagnosis if achieved.",
    )
    confidence: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Final confidence rating.",
    )
    supporting_evidence: list[InvestigationEvidence] = Field(
        default_factory=list,
        description="Structured evidence items gathered during investigation.",
    )
    # Slice 3 Knowledge Grounding extensions
    telemetry_evidence: list[InvestigationEvidence] = Field(
        default_factory=list,
        description="Live telemetry evidence items gathered.",
    )
    knowledge_evidence: list[InvestigationEvidence] = Field(
        default_factory=list,
        description="Organizational knowledge evidence items gathered.",
    )
    retrieval_queries: list[str] = Field(
        default_factory=list,
        description="Knowledge queries executed during investigation.",
    )
    retrieval_mode: str | None = Field(
        default=None,
        description="Mode used for knowledge retrieval.",
    )
    investigation_steps: list[InvestigationStep] = Field(
        default_factory=list,
        description="Executed investigation steps.",
    )

    tool_calls_summary: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Summary of tool queries executed.",
    )
    duration_seconds: float = Field(
        default=0.0,
        description="Duration of investigation in seconds.",
    )
    iteration_count: int = Field(
        default=1,
        description="Number of investigation cycle iterations completed.",
    )
    failure_reason: str | None = Field(
        default=None,
        description="Detailed failure message if investigation failed.",
    )
    completed_at: datetime = Field(
        default_factory=lambda: datetime.now(tz=timezone.utc),
        description="UTC completion timestamp.",
    )

    model_config = {"frozen": False}
