"""
Canonical Action Domain Models for SentinelOps.

Defines:
- `ActionType`: Controlled vocabulary of permitted remediation operations.
- `RiskClass`: Risk tier taxonomy (READ, LOW, MEDIUM, HIGH, CRITICAL).
- `TargetResource`: Abstract infrastructure target identifier.
- `ActionRequest`: Canonical, provider-neutral action specification.
- `ActionStatus`: Lifecycle status of an action execution.
- `ActionResult`: Outcome of an action execution by an ActionProvider.
"""
from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any
from uuid import uuid4

from pydantic import BaseModel, Field


class ActionType(str, Enum):
    """Permitted controlled remediation action types."""

    RESTART_SERVICE = "restart_service"
    ROLLBACK_DEPLOYMENT = "rollback_deployment"
    SCALE_SERVICE = "scale_service"

    # Explicitly rejected / unsupported in this slice
    DELETE_RESOURCE = "delete_resource"
    MODIFY_DATABASE = "modify_database"
    EXECUTE_COMMAND = "execute_command"
    RUN_SHELL = "run_shell"


class RiskClass(str, Enum):
    """Deterministic risk classification taxonomy."""

    READ = "read"
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class TargetResource(BaseModel):
    """Abstract target resource specification."""

    resource_type: str = Field(..., description="e.g. 'service', 'container', 'deployment'")
    resource_id: str = Field(..., description="e.g. 'payments-service', 'auth-service'")
    namespace: str = Field(default="default", description="Environment namespace or cluster boundary")
    cluster: str | None = Field(default=None, description="Optional cluster or region identifier")


class ActionRequest(BaseModel):
    """
    Canonical, provider-neutral action request generated by the SentinelOps agent.
    
    Invariants:
    - Never contains raw bash commands, shell execution strings, or provider-specific APIs.
    - Explicitly references incident ID, supporting evidence IDs, and risk class.
    - Uses `action_id` as execution identity and idempotency key.
    """

    action_id: str = Field(default_factory=lambda: f"ACT-{uuid4().hex[:8]}")
    incident_id: str = Field(..., description="Originating incident identifier")
    action_type: ActionType = Field(..., description="Controlled semantic action type")
    target: TargetResource = Field(..., description="Abstract target resource")
    parameters: dict[str, Any] = Field(default_factory=dict, description="Typed action arguments")
    rationale: str = Field(..., description="Diagnostic justification for proposed action")
    supporting_evidence: list[str] = Field(default_factory=list, description="Cited evidence IDs")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Confidence in action appropriateness")
    requested_by: str = Field(default="sentinelops-agent", description="Actor or agent proposing the action")
    environment: str = Field(default="production", description="Operating environment: 'production', 'staging', etc.")
    risk_class: RiskClass = Field(default=RiskClass.MEDIUM, description="Evaluated risk class")
    created_at: datetime = Field(default_factory=lambda: datetime.now(tz=timezone.utc))


class ActionStatus(str, Enum):
    """Lifecycle status of an action execution."""

    ACCEPTED = "accepted"
    EXECUTING = "executing"
    SUCCEEDED = "succeeded"
    FAILED = "failed"
    REJECTED = "rejected"
    CANCELLED = "cancelled"


class ActionResult(BaseModel):
    """
    Execution outcome reported by an ActionProvider.
    """

    action_id: str = Field(..., description="Corresponding ActionRequest ID")
    status: ActionStatus = Field(..., description="Terminal or progress status")
    provider: str = Field(..., description="Identifier of the executing ActionProvider")
    started_at: datetime = Field(default_factory=lambda: datetime.now(tz=timezone.utc))
    completed_at: datetime | None = Field(default=None)
    result: dict[str, Any] = Field(default_factory=dict, description="Structured execution return data")
    error: str | None = Field(default=None, description="Error message if execution failed")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Provider diagnostic metadata")
