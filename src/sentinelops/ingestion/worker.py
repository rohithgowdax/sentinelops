"""
Telemetry Ingestion Worker for SentinelOps.

Role:
Consumes canonical `TelemetryReceivedEvent` instances from the Redis stream (`sentinel:telemetry`)
and persists them to the PostgreSQL database (`OperationalStore`).

Architectural Principles:
1. AT-LEAST-ONCE DELIVERY & EXPLICIT ACKNOWLEDGEMENT:
   - Worker reads events using `XREADGROUP`.
   - Message is saved to PostgreSQL database FIRST (`store.save_telemetry`).
   - `XACK` is called ONLY IF database persistence succeeds.
   - If database persistence fails or worker crashes, message remains in Redis Pending-Entries List (PEL) for retry.
2. PROVIDER NEUTRALITY:
   - Worker processes `event.telemetry` (`TelemetryRecord`) without inspecting `source.provider`.
   - Handles records generated by `OtelLikeAdapter` and `CustomJsonAdapter` identically.
"""
from __future__ import annotations

import asyncio
import signal

import structlog

from sentinelops.config.settings import get_settings
from sentinelops.integrations.event_bus.redis_bus import RedisEventBus
from sentinelops.storage.postgres_store import PostgresOperationalStore

# Initialize logger
log = structlog.get_logger(__name__)


class TelemetryWorker:
    """
    Ingestion Worker service process.

    Consumes from Redis Streams using consumer groups and writes to PostgreSQL.
    Fully provider-neutral.
    """

    def __init__(
        self,
        event_bus: RedisEventBus,
        store: PostgresOperationalStore,
        consumer_group: str,
        consumer_name: str = "worker-1",
        batch_size: int = 20,
        block_ms: int = 2000,
    ) -> None:
        """
        Initialize the Telemetry Worker service.

        Args:
            event_bus: `RedisEventBus` instance.
            store: `PostgresOperationalStore` instance.
            consumer_group: Redis consumer group name (e.g. 'sentinelops-workers').
            consumer_name: Individual worker worker identifier (e.g. 'worker-1').
            batch_size: Number of messages to read per batch (`count`).
            block_ms: Time in milliseconds to block waiting for stream messages.
        """
        self._bus = event_bus
        self._store = store
        self._group = consumer_group
        self._consumer = consumer_name
        self._batch = batch_size
        self._block = block_ms
        self._running = False

    async def run(self) -> None:
        """
        Start the background ingestion loop.

        Ensures the consumer group exists, then loops continuously calling `_process_batch`.
        Runs until `stop()` is called.
        """
        self._running = True

        # Ensure consumer group is registered in Redis before reading
        await self._bus.ensure_consumer_group(
            self._bus._telemetry_stream, self._group
        )

        log.info(
            "telemetry_worker.started",
            group=self._group,
            consumer=self._consumer,
        )

        while self._running:
            try:
                await self._process_batch()
            except Exception as exc:
                log.error("telemetry_worker.batch_error", error=str(exc), exc_info=True)
                # Sleep briefly to avoid tight error spinning during Redis/DB connection outages
                await asyncio.sleep(1.0)

    async def process_once(self) -> int:
        """
        Process a single batch of telemetry messages and return count of persisted records.

        Primary use: Integration testing without needing a long-running background loop.

        Returns:
            int: Number of records successfully saved and acknowledged.
        """
        await self._bus.ensure_consumer_group(
            self._bus._telemetry_stream, self._group
        )
        return await self._process_batch()

    async def _process_batch(self) -> int:
        """
        Private helper: Fetches a batch of messages from Redis stream and persists them.

        Save-then-ACK Workflow:
        1. Consume stream entries via `self._bus.consume_telemetry(...)`.
        2. Attempt `self._store.save_telemetry(event.telemetry)`.
        3. Upon success, call `self._bus.ack_telemetry(self._group, entry_id)`.
        4. If save fails, log error and skip `ack_telemetry` (retains message in Redis PEL).

        Returns:
            int: Count of successfully persisted messages in this batch.
        """
        count = 0
        async for entry_id, event in self._bus.consume_telemetry(
            group=self._group,
            consumer=self._consumer,
            count=self._batch,
            block_ms=self._block,
        ):
            try:
                # Step 1: Save canonical telemetry to database (idempotent on event_id)
                await self._store.save_telemetry(event.telemetry)

                # Step 2: Acknowledge message in Redis stream
                await self._bus.ack_telemetry(self._group, entry_id)
                count += 1

                log.debug(
                    "telemetry_worker.persisted",
                    event_id=event.event_id,
                    service=event.telemetry.resource.service_name,
                    signal=event.telemetry.signal_type.value,
                )
            except Exception as exc:
                # Log error and DO NOT ACK — message stays in Redis PEL for recovery
                log.error(
                    "telemetry_worker.persist_error",
                    entry_id=entry_id,
                    event_id=event.event_id,
                    error=str(exc),
                )
        return count

    def stop(self) -> None:
        """Signal the worker ingestion loop to stop."""
        self._running = False
        log.info("telemetry_worker.stopping")


async def _run() -> None:
    """
    Async main runner function for the Telemetry Worker CLI process (`sentinelops-worker`).
    """
    settings = get_settings()

    # Initialize PostgreSQL Operational Store connection
    store = PostgresOperationalStore(dsn=settings.postgres_dsn)
    await store.initialize()

    # Initialize Redis EventBus connection
    bus = RedisEventBus(
        redis_url=settings.redis_url,
        telemetry_stream=settings.redis_telemetry_stream,
        incidents_stream=settings.redis_incidents_stream,
    )
    await bus.connect()

    # Initialize TelemetryWorker
    worker = TelemetryWorker(
        event_bus=bus,
        store=store,
        consumer_group=settings.redis_consumer_group,
        batch_size=settings.worker_batch_size,
        block_ms=settings.worker_block_ms,
    )

    # Register UNIX signal handlers for graceful shutdown
    def _shutdown(sig: int, _: object) -> None:
        log.info("worker.shutdown_signal", signal=sig)
        worker.stop()

    signal.signal(signal.SIGTERM, _shutdown)
    signal.signal(signal.SIGINT, _shutdown)

    try:
        await worker.run()
    finally:
        await bus.close()
        await store.close()
        log.info("worker.stopped")


def main() -> None:
    """CLI entrypoint executed by `sentinelops-worker` command."""
    import structlog

    structlog.configure(
        wrapper_class=structlog.make_filtering_bound_logger(20),
    )
    asyncio.run(_run())


if __name__ == "__main__":
    main()
